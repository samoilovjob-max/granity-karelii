const h1Overrides = {};

for (const article of products) {
  const seo = productSeo[article.id];
  if (!seo) throw new Error(`missing seo for ${article.id}`);
  article.seoTitle = seo.seoTitle;
  article.seoDescription = seo.seoDescription;
  if (seo.h1) {
    article.headline = seo.h1;
    h1Overrides[`produkciya/${article.id}.html`] = seo.h1;
  }
  delete article.keywords;
  console.log(article.id, `T${[...seo.seoTitle].length}`, `D${[...seo.seoDescription].length}`);
}

for (const article of stones) {
  const name = stoneNames[article.id] || article.id;
  let title = `${name} оптом от производителя | Партия под машину | Карелия`;
  if ([...title].length > 70) {
    title = `${name} оптом | Партия под машину | Карелия`;
  }
  if ([...title].length > 70) {
    title = `${name} оптом от производителя | Карелия`;
  }
  let seoDescription = `${name} оптом от производителя: изготовим под ваши размеры, индивидуальный расчёт под спецификацию, объём под полную 20-тонную машину, доставка по РФ и ЕАЭС.`;
  if ([...seoDescription].length > 170) {
    seoDescription = `${name} оптом: изготовим под ваши размеры, расчёт под спецификацию, объём под 20-тонную машину, доставка по РФ и ЕАЭС.`;
  }
  article.seoTitle = title;
  article.seoDescription = seoDescription;
  delete article.keywords;
  console.log(article.id, `T${[...title].length}`, `D${[...seoDescription].length}`);
}

